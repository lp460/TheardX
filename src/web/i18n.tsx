export type WebMessageKey = keyof typeof messages.fr;
type I18nContextValue = { language: WebLanguage; setLanguage: (value: WebLanguage) => void };
const I18nContext = createContext<I18nContextValue>({ language: 'fr', setLanguage: () => undefined });
const KEY = 'theardx.web.language';

function initialLanguage(): WebLanguage {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'fr' || saved === 'en' || saved === 'es') return saved;
  } catch { /* Private browsing may disable local storage. */ }
  const language = navigator.language?.slice(0, 2).toLowerCase();
  return language === 'en' || language === 'es' ? language : 'fr';
}

export function WebI18nProvider({ children }: { children: ReactNode }) {
  const [language, changeLanguage] = useState<WebLanguage>(initialLanguage);
  const setLanguage = useCallback((next: WebLanguage) => {
    changeLanguage(next);
    try { localStorage.setItem(KEY, next); } catch { /* optional preference */ }
  }, []);
  useEffect(() => { document.documentElement.lang = language; }, [language]);
  const value = useMemo(() => ({ language, setLanguage }), [language, setLanguage]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useWebI18n() {
  const { language, setLanguage } = useContext(I18nContext);
  const t = useCallback((key: WebMessageKey): string => messages[language][key] ?? messages.fr[key], [language]);
  return {
    language,
    setLanguage,
    t,
  };
}

export function LanguageSelector({ dark = false }: { dark?: boolean }) {
  const { language, setLanguage, t } = useWebI18n();
  return (
    <label className={`inline-flex items-center gap-2 text-sm ${dark ? 'text-white/80' : 'text-muted'}`}>
      <span className="sr-only">{t('language')}</span>
      <select aria-label={t('language')} value={language}
        onChange={(event) => setLanguage(event.target.value as WebLanguage)}
        className={`ts-focus cursor-pointer rounded-xl border px-3 py-2 text-sm font-medium ${dark ? 'border-white/20 bg-white/10 text-white [&>option]:text-black' : 'border-line bg-surface text-fg'}`}>
        <option value="fr">FR</option><option value="en">EN</option><option value="es">ES</option>
      </select>
    </label>
  );
}
